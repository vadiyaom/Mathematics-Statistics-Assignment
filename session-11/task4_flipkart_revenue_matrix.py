"""
Session 11 - Task 4: Flipkart Products Matrix & Revenue Calculation
File: session-11/task4_flipkart_revenue_matrix.py

Description:
Represents a table of 5 Flipkart products with columns for Unit Price and
Quantity Sold as a 5x2 matrix in Python. Implements a dedicated function
`calculate_product_revenues()` that multiplies price by quantity for each row,
calculating the total revenue generated by each product.
"""

import numpy as np

def calculate_product_revenues(matrix: list) -> list:
    """
    Calculates total revenue for each product in a price-quantity matrix.

    Args:
        matrix (list of list): 5x2 matrix where:
            matrix[i][0] = Unit Price
            matrix[i][1] = Quantity Sold

    Returns:
        list of dict: Revenue details for each product row.
    """
    revenues = []
    for row_idx, row in enumerate(matrix):
        price = row[0]
        quantity = row[1]
        revenue = price * quantity
        revenues.append({
            "product_index": row_idx,
            "price": price,
            "quantity": quantity,
            "revenue": revenue
        })
    return revenues


def run_task4():
    # -------------------------------------------------------------
    # 1. Dataset: 5 Flipkart Products (5x2 Matrix)
    # Columns: [Price in INR, Quantity Sold]
    # -------------------------------------------------------------
    product_names = [
        "Product 1: Wireless Earbuds",
        "Product 2: Smartphone Case",
        "Product 3: 10000mAh Power Bank",
        "Product 4: 65W Fast Charger",
        "Product 5: Bluetooth Speaker"
    ]

    # 5x2 Matrix: [[Price, Quantity], ...]
    flipkart_matrix = [
        [1499, 50],   # Earbuds
        [299, 120],   # Phone Case
        [999, 40],    # Power Bank
        [499, 85],    # Fast Charger
        [1999, 30]    # Bluetooth Speaker
    ]

    # -------------------------------------------------------------
    # 2. Function Call: Calculate Revenue for Each Product
    # -------------------------------------------------------------
    revenue_details = calculate_product_revenues(flipkart_matrix)

    # Convert to NumPy 2D array for vector multiplication
    np_matrix = np.array(flipkart_matrix)
    prices = np_matrix[:, 0]
    quantities = np_matrix[:, 1]
    np_revenues = prices * quantities
    total_store_revenue = np.sum(np_revenues)

    # -------------------------------------------------------------
    # 3. Formatted Matrix and Revenue Output
    # -------------------------------------------------------------
    print("=" * 75)
    print(" TASK 4: FLIPKART PRODUCTS REVENUE CALCULATION (5x2 MATRIX)")
    print("=" * 75)
    print("Raw Python 5x2 Matrix [Price, Quantity]:")
    print(flipkart_matrix)
    print("\nNumPy 5x2 Matrix:")
    print(np_matrix)
    print("-" * 75)

    print(f"{'#':<3} | {'Product Name':<30} | {'Price (Rs)':<12} | {'Qty Sold':<10} | {'Total Revenue (Rs)':<18}")
    print("-" * 75)
    for idx, (name, item) in enumerate(zip(product_names, revenue_details), 1):
        rev = item["revenue"]
        print(f"{idx:<3} | {name:<30} | Rs. {item['price']:<8} | {item['quantity']:<10} | Rs. {rev:<14,}")
    print("=" * 75)

    # -------------------------------------------------------------
    # 4. Summary & Revenue Insights
    # -------------------------------------------------------------
    print(f"{'TOTAL STORE REVENUE':<48} | {np.sum(quantities):<10} | Rs. {total_store_revenue:<14,}")
    print("=" * 75)

    print("\nREVENUE BREAKDOWN & ANALYSIS:")
    print("-" * 75)
    for name, rev in zip(product_names, np_revenues):
        pct = (rev / total_store_revenue) * 100
        print(f"{name:<32} : Rs. {rev:<8,} ({pct:.2f}% of total revenue)")
    print("-" * 75)
    print(f"Top Revenue Generating Product : {product_names[np.argmax(np_revenues)]} (Rs. {np.max(np_revenues):,})")
    print(f"Highest Volume Product Sold    : {product_names[np.argmax(quantities)]} ({np.max(quantities)} units)")
    print("=" * 75)


if __name__ == "__main__":
    run_task4()

